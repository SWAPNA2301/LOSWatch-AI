-- LOSWatch-AI Phase 7A. Identifiers are rendered from validated environment
-- configuration by loswatch.snowflake; values are always bound parameters.
CREATE SCHEMA IF NOT EXISTS {{DATABASE}}.{{SCHEMA}};

CREATE TABLE IF NOT EXISTS {{DATABASE}}.{{SCHEMA}}.LOSWATCH_HISTORICAL_ENCOUNTERS (
    RECORD_KEY STRING NOT NULL,
    SOURCE_BATCH_ID STRING NOT NULL,
    AGE_BAND STRING,
    GENDER STRING,
    ADMISSION_TYPE_ID STRING,
    ADMISSION_SOURCE_ID STRING,
    NUMBER_OUTPATIENT NUMBER,
    NUMBER_EMERGENCY NUMBER,
    NUMBER_INPATIENT NUMBER,
    ACTUAL_LOS_DAYS NUMBER,
    RECORD_HASH STRING NOT NULL,
    SYNCED_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS {{DATABASE}}.{{SCHEMA}}.LOSWATCH_PREDICTION_LOGS (
    PREDICTION_KEY STRING NOT NULL,
    SOURCE_BATCH_ID STRING NOT NULL,
    MODEL_VERSION STRING NOT NULL,
    PREDICTED_LOS_DAYS FLOAT NOT NULL,
    FEATURE_FINGERPRINT STRING,
    CREATED_UTC TIMESTAMP_TZ,
    RECORD_HASH STRING NOT NULL,
    SYNCED_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS {{DATABASE}}.{{SCHEMA}}.LOSWATCH_DRIFT_REPORTS (
    REPORT_KEY STRING NOT NULL,
    SOURCE_BATCH_ID STRING NOT NULL,
    MODEL_ID STRING NOT NULL,
    SCENARIO STRING,
    CREATED_UTC TIMESTAMP_TZ,
    REFERENCE_SIZE NUMBER,
    CURRENT_SIZE NUMBER,
    DRIFT_DETECTED BOOLEAN,
    REPORT_JSON VARIANT NOT NULL,
    RECORD_HASH STRING NOT NULL,
    SYNCED_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS {{DATABASE}}.{{SCHEMA}}.LOSWATCH_MODEL_VERSIONS (
    MODEL_VERSION STRING NOT NULL,
    SOURCE_BATCH_ID STRING NOT NULL,
    MODEL_ID STRING,
    STATUS STRING,
    CREATED_UTC TIMESTAMP_TZ,
    SELECTED_MODEL STRING,
    METRICS_JSON VARIANT NOT NULL,
    RECORD_HASH STRING NOT NULL,
    SYNCED_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS {{DATABASE}}.{{SCHEMA}}.LOSWATCH_RETRAINING_AUDIT_EVENTS (
    EVENT_KEY STRING NOT NULL,
    SOURCE_BATCH_ID STRING NOT NULL,
    ACTION STRING NOT NULL,
    MODEL_VERSION STRING,
    TIMESTAMP_UTC TIMESTAMP_TZ,
    APPROVED_BY STRING,
    DETAILS_JSON VARIANT NOT NULL,
    RECORD_HASH STRING NOT NULL,
    SYNCED_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP()
);
